<?php

declare(strict_types=1);

namespace Systopic\Cms\Tables\Pages;

use Systopic\Cms\Tables\Pages\Model as PageRow;
use Systopic\Cms\Tables\Rewritepaths\Model as Rewritepath;
use Systopic\Cms\Tables\Rewritepaths\Operator as PathOperator;
use Systopic\Cms\Queries\RewritepathLookup\RewritepathLookup;
use Systopic\Db\Scope;
use Systopic\Cms\Queries\Params;
use Systopic\Cms\Pages\Sites\NodeSite;

/**
 * The addresses of a place in the tree — successor of
 * `pageRewritepathFuncs` and of the read side of `pageRewritepath`.
 *
 * **`Urls` is only the name of the panel in the sidebar.** The table and the
 * row class are called `Rewritepath`, and this collaborator is named after
 * what it manages: the paths of a page and the addresses built from them.
 *
 * It hangs off the `Page`, not off the `Page`, and that is not a formality:
 * `link` and `href` depend on the **place in the tree**, not on the content.
 * An alias carries the page of its original but gets its own id appended —
 * `.../path/42/` — and a path starting with `#` is measured against the path
 * of its *parent*. Only the node knows either.
 *
 * Three differences to the legacy code:
 *
 * **1. Reading creates nothing.** `pageRewritepath::get()` writes: if a path
 * is missing it builds one, saves it and returns it — in the middle of
 * rendering. Here `primary` returns `null` instead, and creating is a call of
 * its own. A read path that writes is the reason a preview leaves a row in the
 * database behind.
 *
 * **2. All paths cost one statement per level**, not one per page.
 *
 * **3. `hash` is not a special case inside the string.** The legacy code
 * checks `strpos($rwstring, '#') === 0` in four places; here the question is
 * asked once.
 */
final class Rewritepaths
{
    /** @var list<Rewritepath>|null */
    private ?array $allPaths = null;

    public function __construct(
        private readonly Scope $scope,
        private readonly Params $params,
        private readonly Page $page,
    ) {}

    // ----------------------------------------------------------- the rows

    /** @var list<Rewritepath> every path of this page, primary one first */
    public array $all {
        get => $this->allPaths ??= $this->page->generationFor()->rewritepathsOf($this->page->node);
    }

    /**
     * The path the page is reachable under.
     *
     * NULL means "there is none" — in the legacy code the same access creates
     * one instead.
     */
    public ?Rewritepath $primary {
        get {
            foreach ($this->all as $path) {
                if ($path->isPrimary) {
                    return $path;
                }
            }
            return null;
        }
    }

    /** @var list<Rewritepath> the ones generated by the system */
    public array $auto {
        get => array_values(array_filter($this->all, static fn($p) => $p->autoIndex !== null));
    }

    /** @var list<Rewritepath> the ones entered by hand */
    public array $custom {
        get => array_values(array_filter($this->all, static fn($p) => $p->autoIndex === null));
    }

    // ---------------------------------------------------------- the path

    /** The raw entry, without a slash and without the parent. */
    public ?string $string {
        get => $this->primary?->string;
    }

    /** A path starting with `#` points at a spot on the parent page. */
    public bool $isHash {
        get => str_starts_with((string) $this->string, '#');
    }

    /** The entry without a leading `#` — `$rewritepath->name` in the legacy code. */
    public ?string $name {
        get => $this->string === null ? null : preg_replace('~^#~', '', $this->string);
    }

    /** The part after the `#`, NULL otherwise — `$page->hashvalue` before. */
    public ?string $hashvalue {
        get => $this->isHash ? substr((string) $this->string, 1) : null;
    }

    /**
     * The path as an address needs it — with a trailing slash.
     *
     * The same thing `pageRewritepath::__toString()` returns, only without the
     * fallback that prints `?id=…&lang=…` for a missing string and dumps the
     * record along the way.
     */
    public string $path {
        get {
            $entry = $this->string;
            if ($entry === null || $entry === '') {
                return '';
            }
            if ($this->isHash) {
                return $this->page->parent?->rewritepaths->path . $entry;
            }
            return $entry . '/';
        }
    }

    /**
     * An alias appends its own node id; otherwise original and alias would
     * point at the same address.
     */
    public string $appendix {
        get => $this->page->isAlias ? $this->page->node->id . '/' : '';
    }

    // ------------------------------------------------------------ addresses

    /**
     * The address inside the application.
     *
     * In the CMS it points at the page panel, on the site at the page; if the
     * node redirects somewhere, that target's address applies.
     */
    public string $link {
        get {
            if ($this->params->inCms) {
                return $this->params->root . 'cms/pages/?id=' . $this->page->node->id
                     . '&lang=' . $this->params->lang;
            }
            $target = $this->page->redirectsTo;
            if ($target !== null) {
                return $target->rewritepaths->link;
            }
            // Inside the site the request came in for the link stays relative;
            // a page of another site is addressed on that site's host.
            $site = $this->addressSite;
            $root = $site === NodeSite::currentSiteNodeId() ? $this->params->root : NodeSite::linkRoot($site);
            return $root . $this->path . $this->appendix;
        }
    }

    /** The same address absolute — for everything that leaves the house. */
    public string $href {
        get {
            $site = $this->addressSite;
            $root = $site === NodeSite::currentSiteNodeId() ? $this->params->siteUrl : NodeSite::hrefRoot($site);
            return $root . $this->path . $this->appendix;
        }
    }

    /**
     * The site the address belongs to: the copy the primary path carries —
     * no tree lookup; a page without a path asks the tree.
     */
    private ?int $addressSite {
        get {
            $primary = $this->primary;
            return $primary !== null ? $primary->siteNodeId : NodeSite::siteNodeIdOf($this->page->id);
        }
    }

    /**
     * The site every path of this page carries: the node of type 'site' above
     * it, NULL for the default site — see Rewritepaths\Model::$siteNode.
     */
    public ?int $siteNodeId {
        get => NodeSite::siteNodeIdOf($this->page->id);
    }

    /** The same as a relation value for a new or changed path row. */
    private function siteNodeFor(?int $siteNodeId): ?\Systopic\System\Tables\Nodes\Model
    {
        return $siteNodeId === null ? null : \Systopic\System\Tables\Nodes\Model::withId($siteNodeId);
    }

    public function __toString(): string
    {
        return $this->path;
    }

    // --------------------------------------------------------------- writing
    //
    // Each method changes rows and hands back the ones to save, or the one to
    // remove; the caller owns the `UnitOfWork`. The lists above follow at
    // once, so the sidebar renders the new state without loading again.

    /** One path of this page by its id — NULL for somebody else's. */
    public function byId(int $id): ?Rewritepath
    {
        foreach ($this->all as $path) {
            if ($path->id === $id) {
                return $path;
            }
        }
        return null;
    }

    /**
     * A custom path, unique over the installation: `NEW_URL`, `NEW_URL_1` …
     *
     * @return Rewritepath the new row, not yet saved
     */
    public function newCustom(string $base = 'NEW_URL'): Rewritepath
    {
        $row = $this->pageRow();
        $string = $base;
        // No page excluded: the page's own paths count too. Excluding it
        // (right for rebuildAuto, where the old path must not block the new
        // one) let every click add one more identical 'NEW_URL' to the page.
        $site = $this->siteNodeId;
        for ($n = 1; !RewritepathLookup::isUnique($this->scope, $string, null, $site); $n++) {
            if ($n > 100) {
                throw new \RuntimeException("rewritepaths: no free path for '$base' after 100 attempts");
            }
            $string = $base . '_' . $n;
        }
        $path = new Rewritepath();
        $path->page = $row;
        $path->siteNode = $this->siteNodeFor($site);
        $path->string = $string;
        $path->isPrimary = false;
        $path->autoIndex = null;
        $this->attach($path);
        return $path;
    }

    /**
     * The automatic path, built from the label — `pageRewritepathFuncs::createOrUpdate()`.
     *
     * The ideal is the label itself. If another page holds it, the label of
     * the branch's root goes in front, and if that is taken too, `_1`, `_2` …
     * are appended; `autoIndex` counts the steps away from the ideal and
     * `barrierId` names the path that stood in the way.
     *
     * Two things differ from the legacy code: the root label goes through the
     * same `safeStr()` as the page label (it used to be prepended raw, spaces
     * and all), and a new automatic path only becomes primary when the page
     * has no primary path yet (it used to make a second one).
     *
     * @return list<Rewritepath> the rows to save
     */
    public function rebuildAuto(): array
    {
        $row = $this->pageRow();
        $site = $this->siteNodeId;
        $string = PathOperator::fromLabel((string) $row->label);
        // A page without a label gets its node id as its path, never '': ''
        // is the start page's address, and a second '' takes the start
        // page's place in the resolver (galerie, 2026-10-26: "rebuild all"
        // gave an unnamed, unpublished artist page the address of the home
        // page, and the site showed nothing).
        if ($string === '') {
            $string = 'page_' . $this->page->id;
        }
        $autoIndex = 0;
        $barrier = null;

        $blocker = RewritepathLookup::blocker($this->scope, $string, $row->id, $site);
        if ($blocker !== null) {
            $barrier = $blocker->id;
            $root = $this->page->root;
            $rootSegment = PathOperator::fromLabel((string) ($root->row?->label ?? ''));
            if ($root !== $this->page && $rootSegment !== '') {
                $string = $rootSegment . '/' . $string;
                $autoIndex++;
            }
            $base = $string;
            for ($n = 1; !RewritepathLookup::isUnique($this->scope, $string, $row->id, $site); $n++) {
                if ($n > 100) {
                    throw new \RuntimeException("rewritepaths: no free path for '$base' after 100 attempts");
                }
                $autoIndex++;
                $string = $base . '_' . $n;
            }
        }

        $existing = $this->auto;
        if ($existing !== []) {
            $changed = [];
            foreach ($existing as $path) {
                // The empty path is the start page's; it is never rebuilt.
                // (The legacy spelled that "auto_index > 0", which also froze
                // every ideal path, index 0, at its first label.)
                if ($path->string === '') {
                    continue;
                }
                if ($path->string !== $string
                    || $path->autoIndex !== $autoIndex
                    || $path->barrierId !== $barrier
                    || $path->siteNodeId !== $site) {
                    $path->string = $string;
                    $path->autoIndex = $autoIndex;
                    $path->barrierId = $barrier;
                    $path->siteNode = $this->siteNodeFor($site);
                    $changed[] = $path;
                }
            }
            return $changed;
        }

        $path = new Rewritepath();
        $path->page = $row;
        $path->siteNode = $this->siteNodeFor($site);
        $path->string = $string;
        $path->isPrimary = $this->primary === null;
        $path->autoIndex = $autoIndex;
        $path->barrierId = $barrier;
        $this->attach($path);
        return [$path];
    }

    /**
     * Make one path the primary one.
     *
     * @return list<Rewritepath> the rows to save
     */
    public function makePrimary(Rewritepath $primary): array
    {
        return PathOperator::makePrimary($this->all, $primary);
    }

    /** A path leaves the lists — the caller removes the row. */
    public function detach(Rewritepath $path): void
    {
        $this->allPaths = array_values(array_filter($this->all, static fn($p) => $p !== $path));
        $this->page->generationFor()->detachRewritepath((int) $this->pageRow()->id, $path);
    }

    private function attach(Rewritepath $path): void
    {
        $all = $this->all;
        $all[] = $path;
        $this->allPaths = $all;
        $pageId = $this->pageRow()->id;
        if ($pageId !== null) {
            $this->page->generationFor()->attachRewritepath($pageId, $path);
        }
    }

    private function pageRow(): PageRow
    {
        return $this->page->row
            ?? throw new \RuntimeException('rewritepaths: node ' . $this->page->id . ' has no page in ' . $this->params->lang);
    }
}
