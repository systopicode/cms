import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const {chromium}=await import(process.env.FLUXO_PLAYWRIGHT_MODULE);
const browser=await chromium.launch({channel:'chrome',headless:true});
try {
 const page=await browser.newPage(); const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.setContent('<div data-editor-presence data-node="9" data-lang="en" data-endpoint="/presence" hidden></div>');
 await page.evaluate(()=>{
  window.noticeFrames=[];
  const animate=Element.prototype.animate;
  Element.prototype.animate=function(frames,options){
   if(this.matches('[data-editor-presence]')) noticeFrames.push(frames);
   return animate.call(this,frames,options);
  };
  window.reply={available:true,others:1,names:['Another editor'],revision:'first'};
  window.calls=[];window.leaveRequests=[];window.fetch=(url,options)=>{leaveRequests.push({url,...options});return Promise.resolve({});};
  window.sys={http:{parseURL(){}},core:{server:{}}};
  sys.core.server.call=function(input){calls.push(input)};
  sys.core.server.call.prototype.send=function(){calls.at(-1).background=this.background;return {done(fn){fn(reply);return this},fail(){return this}}};
 });
 const source=await readFile('panels/admin/010_pages/pages.js','utf8');
 await page.addScriptTag({content:source.slice(source.indexOf('// Advisory only:'))});
 assert.match(await page.locator('[data-editor-presence]').innerText(),/[Aa]lso open: Another editor/);
 assert.equal(await page.evaluate(()=>noticeFrames[0]?.[0]?.height),'0px','opening animates from zero height');
 assert.equal(await page.locator('#pageEditConflict').count(),0);
 await page.evaluate(()=>window.dispatchEvent(new PageTransitionEvent('pagehide')));
 assert.equal(await page.evaluate(()=>JSON.parse(leaveRequests[0].body).leave),1,'closing document sends a departure');
 assert.equal(await page.evaluate(()=>leaveRequests[0].keepalive),true,'departure survives document teardown');
 assert.equal(await page.evaluate(()=>calls.every(c=>c.method==='put' && c.background===true)),true,'advisory polls are background calls');
 await page.evaluate(()=>{const old=document.querySelector('[data-editor-presence]');const replacement=old.cloneNode(false);replacement.hidden=true;old.replaceWith(replacement);document.dispatchEvent(new Event('cms:rendered'));window.restoredSynchronously=!replacement.hidden;});
 assert.equal(await page.evaluate(()=>restoredSynchronously),true,'known advisory restored before repaint, without a whole-page refresh');
 await page.evaluate(()=>{const n=document.querySelector('[data-editor-presence]');n.dataset.node='10';document.dispatchEvent(new Event('cms:rendered'))});
 await page.waitForFunction(()=>calls.at(-1).id==='10');
 assert.equal(await page.evaluate(()=>calls.at(-1).id),'10','tree navigation checks the newly selected page immediately');
 await page.evaluate(()=>{document.querySelector('[data-editor-presence]').dataset.node='11';reply={available:true,others:0,revision:'second'};document.dispatchEvent(new Event('cms:rendered'))});
 await page.locator('[data-editor-presence]').waitFor({state:'hidden'});
 assert.equal(await page.locator('[data-editor-presence]').isVisible(),false);
 await page.evaluate(()=>{reply={available:true,others:1,revision:'second'};document.dispatchEvent(new Event('cms:rendered'))});
 await page.locator('[data-editor-presence]').waitFor({state:'visible'});
 await page.evaluate(()=>{reply={available:true,others:0,revision:'second'};document.dispatchEvent(new Event('cms:rendered'))});
 await page.waitForTimeout(70);
 await page.evaluate(()=>{reply={available:true,others:1,revision:'second'};document.dispatchEvent(new Event('cms:rendered'))});
 await page.waitForTimeout(350);
 assert.equal(await page.locator('[data-editor-presence]').isVisible(),true,'returning editor cancels a pending hide animation');
 assert.deepEqual(errors,[],'no Promise.cancel or stale-animation exception');
 await page.evaluate(()=>{document.querySelector('[data-editor-presence]').remove();document.dispatchEvent(new Event('cms:rendered'))});
 await page.waitForFunction(()=>calls.at(-1).leave===1);
 const early=await browser.newPage();
 const earlyErrors=[];early.on('pageerror',error=>earlyErrors.push(error.message));
 await early.addInitScript({content:`window.calls=[];window.sys={http:{parseURL(){}},core:{server:{}}};sys.core.server.call=function(input){calls.push(input)};sys.core.server.call.prototype.send=function(){return {done(fn){fn({available:true,others:1,revision:'head'});return this},fail(){return this}}};`+source.slice(source.indexOf('// Advisory only:'))});
 await early.goto('data:text/html,<div data-editor-presence data-node="12" data-lang="en" data-endpoint="/presence" hidden></div>');
 await early.locator('[data-editor-presence]').waitFor({state:'visible'});
 assert.deepEqual(earlyErrors,[],'script in the head waits for body before observing');
 await early.close();
 const reloadPage=await browser.newPage();
 await reloadPage.route('http://presence.test/**',r=>r.fulfill({contentType:'text/html',body:'<div data-editor-presence data-node="9" data-lang="en" data-endpoint="/presence" hidden></div>'}));
 await reloadPage.addInitScript({content:`window.calls=[];window.sys={http:{parseURL(){}},core:{server:{}}};sys.core.server.call=function(input){calls.push(input)};sys.core.server.call.prototype.send=function(){return {done(fn){fn({available:true,others:0,revision:'same'});return this},fail(){return this}}};`+source.slice(source.indexOf('// Advisory only:'))});
 await reloadPage.goto('http://presence.test/');
 const firstClient=await reloadPage.evaluate(()=>calls[0].client);
 await reloadPage.reload();
 assert.notEqual(await reloadPage.evaluate(()=>calls[0].client),firstClient,'new document has its own identity');
 assert.equal(await reloadPage.evaluate(()=>calls[0].previousClient),firstClient,'reload retires previous document heartbeat');
 assert.equal(await reloadPage.locator('[data-editor-presence]').isVisible(),false,'single reloaded tab stays quiet');
 await reloadPage.close();
 console.log('ok: advisory is nonblocking, AJAX navigation checks immediately, single editor stays quiet');
} finally {await browser.close()}
