import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const {chromium}=await import(process.env.FLUXO_PLAYWRIGHT_MODULE);
const browser=await chromium.launch({channel:'chrome',headless:true});
// A stand-in for sys.core.server: header hooks only, no requests of its own.
const fakeServer=`window.sys={core:{server:{hooks:[],addHeaders(fn){this.hooks.push(fn)},headersFor(m){return Object.assign({},...this.hooks.map(fn=>fn(m)))}}}};`;
const marker=node=>`<div data-editor-presence data-node="${node}" data-lang="en" data-endpoint="/presence" hidden></div>`;
try {
 const source=await readFile('panels/admin/010_pages/pages.js','utf8');
 const block=source.slice(source.indexOf('// Advisory only:'));
 assert.equal(/setInterval|setTimeout/.test(block.slice(0,block.indexOf('// A remembered selection'))),false,'presence runs no timer');
 const page=await browser.newPage(); const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.setContent(marker(9));
 await page.evaluate(()=>{
  window.noticeFrames=[];
  const animate=Element.prototype.animate;
  Element.prototype.animate=function(frames,options){
   if(this.matches('[data-editor-presence]')) noticeFrames.push(frames);
   return animate.call(this,frames,options);
  };
  window.leaveRequests=[];window.fetch=(url,options)=>{leaveRequests.push({url,...options});return Promise.resolve({});};
 });
 await page.addScriptTag({content:fakeServer+block});
 const headers=await page.evaluate(()=>sys.core.server.headersFor('put'));
 assert.equal(headers['X-Editor-Page'],'9:en','every request names the page of this tab');
 assert.match(headers['X-Editor-Client'],/^[a-zA-Z0-9-]{16,80}$/);
 await page.waitForTimeout(300);
 assert.equal(await page.locator('[data-editor-presence]').isVisible(),false,'nothing shows before an answer');
 await page.evaluate(()=>cmsPresence({node:'9',lang:'en',available:true,others:1,names:['Another editor'],revision:'first'}));
 assert.match(await page.locator('[data-editor-presence]').innerText(),/[Aa]lso open: Another editor/);
 assert.equal(await page.evaluate(()=>noticeFrames[0]?.[0]?.height),'0px','opening animates from zero height');
 await page.evaluate(()=>window.dispatchEvent(new PageTransitionEvent('pagehide')));
 assert.equal(await page.evaluate(()=>leaveRequests[0].headers['X-Editor-Leave']),'1','closing document sends a departure');
 assert.equal(await page.evaluate(()=>leaveRequests[0].keepalive),true,'departure survives document teardown');
 await page.evaluate(()=>{const old=document.querySelector('[data-editor-presence]');const replacement=old.cloneNode(false);replacement.hidden=true;old.replaceWith(replacement);document.dispatchEvent(new Event('cms:rendered'));window.restoredSynchronously=!replacement.hidden;});
 assert.equal(await page.evaluate(()=>restoredSynchronously),true,'known advisory restored before repaint, without a request');
 await page.evaluate(()=>{document.querySelector('[data-editor-presence]').dataset.node='10';});
 assert.equal(await page.evaluate(()=>sys.core.server.headersFor('get')['X-Editor-Page']),'10:en','next request names the newly shown page');
 await page.evaluate(()=>cmsPresence({node:'9',lang:'en',available:true,others:1,revision:'first'}));
 await page.evaluate(()=>cmsPresence({node:'10',lang:'en',available:true,others:0,revision:'a'}));
 await page.locator('[data-editor-presence]').waitFor({state:'hidden'});
 await page.evaluate(()=>cmsPresence({node:'10',lang:'en',available:true,others:0,revision:'b'}));
 assert.match(await page.locator('[data-editor-presence]').innerText(),/updated/,'a revision changed by someone else is reported');
 await page.evaluate(()=>{(window.cmsOwnPageSaves ||= new Set()).add('10:en');cmsPresence({node:'10',lang:'en',available:true,others:0,revision:'c'})});
 await page.locator('[data-editor-presence]').waitFor({state:'hidden'});
 await page.evaluate(()=>cmsPresence({node:'10',lang:'en',available:true,others:1,revision:'c'}));
 await page.locator('[data-editor-presence]').waitFor({state:'visible'});
 await page.evaluate(()=>cmsPresence({node:'10',lang:'en',available:true,others:0,revision:'c'}));
 await page.waitForTimeout(70);
 await page.evaluate(()=>cmsPresence({node:'10',lang:'en',available:true,others:1,revision:'c'}));
 await page.waitForTimeout(350);
 assert.equal(await page.locator('[data-editor-presence]').isVisible(),true,'returning editor cancels a pending hide animation');
 await page.evaluate(()=>document.querySelector('[data-editor-presence]').remove());
 assert.equal(await page.evaluate(()=>'X-Editor-Page' in sys.core.server.headersFor('get')),false,'without a page the request names none');
 assert.deepEqual(errors,[],'no Promise.cancel or stale-animation exception');
 const early=await browser.newPage();
 const earlyErrors=[];early.on('pageerror',error=>earlyErrors.push(error.message));
 await early.addInitScript({content:fakeServer+block});
 await early.goto('data:text/html,'+marker(12));
 assert.equal(await early.evaluate(()=>sys.core.server.headersFor('get')['X-Editor-Page']),'12:en');
 assert.deepEqual(earlyErrors,[],'script in the head works before the body exists');
 await early.close();
 const reloadPage=await browser.newPage();
 await reloadPage.route('http://presence.test/**',r=>r.fulfill({contentType:'text/html',body:marker(9)}));
 await reloadPage.addInitScript({content:fakeServer+block});
 await reloadPage.goto('http://presence.test/');
 const firstClient=await reloadPage.evaluate(()=>sys.core.server.headersFor('get')['X-Editor-Client']);
 await reloadPage.reload();
 const first=await reloadPage.evaluate(()=>sys.core.server.headersFor('get'));
 assert.notEqual(first['X-Editor-Client'],firstClient,'new document has its own identity');
 assert.equal(first['X-Editor-Previous'],firstClient,'reload retires the previous document');
 assert.equal('X-Editor-Previous' in await reloadPage.evaluate(()=>sys.core.server.headersFor('get')),false,'retired once');
 await reloadPage.close();
 console.log('ok: advisory is nonblocking, travels with requests, runs no timer');
} finally {await browser.close()}
